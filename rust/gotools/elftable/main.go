// Command elftable writes the names Go's debug/elf gives ELF machines and file types (Machine.String, Type.String), which
// heimdalld immunity puts in a held program's report, so the Rust port names them as Go does. Go names a value it does not
// know after a known one ("EM_ALPHA_STD+9958"), so the table is every value from 0 to 65535 as runs: from, to, the name,
// and the number added to the first value of the run (none for a value Go names itself).
//
//	go run ./rust/gotools/elftable > rust/heimdall/src/cli/immunity/elf_table.rs
package main

import (
	"debug/elf"
	"fmt"
	"runtime"
	"strconv"
	"strings"
)

func runs(name string, str func(int) string) {
	fmt.Printf("pub static %s: &[(u16, u16, &str, Option<u32>)] = &[\n", name)
	type run struct {
		from, to int
		base     string
		off      int // -1: exact
	}
	var cur *run
	flush := func() {
		if cur == nil {
			return
		}
		off := "None"
		if cur.off >= 0 {
			off = fmt.Sprintf("Some(%d)", cur.off)
		}
		fmt.Printf("    (%d, %d, %q, %s),\n", cur.from, cur.to, cur.base, off)
		cur = nil
	}
	for i := 0; i < 65536; i++ {
		s := str(i)
		base, off := s, -1
		if j := strings.LastIndexByte(s, '+'); j >= 0 {
			n, err := strconv.Atoi(s[j+1:])
			if err == nil {
				base, off = s[:j], n
			}
		}
		if cur != nil && off >= 0 && cur.off >= 0 && base == cur.base && off == cur.off+(i-cur.from) {
			cur.to = i
			continue
		}
		flush()
		cur = &run{from: i, to: i, base: base, off: off}
	}
	flush()
	fmt.Printf("];\n\n")
}

func main() {
	fmt.Printf("// Generated by rust/gotools/elftable from %s; do not edit.\n\n", runtime.Version())
	fmt.Printf("/// Go's elf.Machine(n).String(), as runs.\n")
	runs("MACHINES", func(i int) string { return elf.Machine(i).String() })
	fmt.Printf("/// Go's elf.Type(n).String(), as runs.\n")
	runs("TYPES", func(i int) string { return elf.Type(i).String() })
}
