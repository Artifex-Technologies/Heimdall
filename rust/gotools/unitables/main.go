// Command unitables writes the Unicode tables the Rust port needs to behave exactly as the Go daemon does: which characters
// Go's strconv.Quote prints as they are (unicode.IsPrint), which are format characters (unicode.Cf, the invisible-unicode
// detector) and which are spaces (unicode.IsSpace, strings.Fields). Rust's own tables follow the Unicode version of its
// standard library; these follow the Go that built heimdalld, so a character added in a newer Unicode is judged alike.
//
//	go run ./rust/gotools/unitables > rust/heimdall/src/gotext/tables.rs
package main

import (
	"fmt"
	"os"
	"runtime"
	"unicode"
)

func ranges(name string, in func(rune) bool, from rune) {
	fmt.Printf("pub static %s: &[(u32, u32)] = &[\n", name)
	n := 0
	for r := from; r <= unicode.MaxRune; r++ {
		if !in(r) {
			continue
		}
		lo := r
		for r+1 <= unicode.MaxRune && in(r+1) {
			r++
		}
		fmt.Printf("    (0x%04X, 0x%04X),\n", lo, r)
		n++
	}
	fmt.Printf("];\n\n")
	fmt.Fprintf(os.Stderr, "%s: %d ranges\n", name, n)
}

func main() {
	fmt.Printf("// Generated by rust/gotools/unitables from %s (Unicode %s). Do not edit by hand.\n\n", runtime.Version(), unicode.Version)
	fmt.Printf("/// The Unicode version of the Go these tables came from.\npub const GO_UNICODE_VERSION: &str = %q;\n\n", unicode.Version)
	fmt.Println("/// Characters at or above U+0080 that Go's unicode.IsPrint accepts (strconv.Quote prints them as they are).")
	ranges("PRINT", unicode.IsPrint, 0x80)
	fmt.Println("/// Go's unicode.Cf (format characters).")
	ranges("CF", func(r rune) bool { return unicode.Is(unicode.Cf, r) }, 0)
	fmt.Println("/// Go's unicode.IsSpace (strings.Fields and strings.TrimSpace split and trim on these).")
	ranges("SPACE", unicode.IsSpace, 0)
}
