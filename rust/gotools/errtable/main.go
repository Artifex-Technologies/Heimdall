// Command errtable writes Go's texts for the kernel's error numbers (syscall.Errno.Error), which the one-shot commands print
// inside Go's "open PATH: TEXT" errors. Go keeps its own table (mostly glibc's with a lowercase first letter, but not always),
// so the Rust port carries Go's.
//
//	go run ./rust/gotools/errtable > rust/heimdall/src/goerr_table.rs
package main

import (
	"fmt"
	"runtime"
	"syscall"
)

func main() {
	fmt.Printf("// Generated by rust/gotools/errtable from %s; do not edit.\n\n", runtime.Version())
	fmt.Printf("/// Go's syscall.Errno(n).Error() for n in 0..134.\n")
	fmt.Printf("pub static ERRNO: [&str; 134] = [\n")
	for i := 0; i < 134; i++ {
		fmt.Printf("    %q,\n", syscall.Errno(i).Error())
	}
	fmt.Printf("];\n")
}
