// Command foldtable writes Go's simple case folding as the Rust port needs it for strings.EqualFold: for every rune that folds
// to another, the smallest rune of its orbit (unicode.SimpleFold walks the orbit in increasing order, so two runes are equal
// under EqualFold exactly when their orbits' smallest runes are the same). The table follows the Go that built heimdalld.
//
//	go run ./rust/gotools/foldtable > rust/heimdall/src/cli/lan/fold_table.rs
package main

import (
	"fmt"
	"runtime"
	"unicode"
)

func main() {
	fmt.Printf("// Generated by rust/gotools/foldtable from %s (Unicode %s); do not edit.\n\n", runtime.Version(), unicode.Version)
	fmt.Printf("/// (rune, the smallest rune of its case-folding orbit), for every rune whose orbit has more than one rune and which is not\n/// that smallest one, in rune order.\n")
	fmt.Printf("pub static FOLD: &[(u32, u32)] = &[\n")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		min := r
		for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
			if f < min {
				min = f
			}
		}
		if min != r {
			fmt.Printf("    (0x%04X, 0x%04X),\n", r, min)
		}
	}
	fmt.Printf("];\n")
}
