#!/usr/bin/env python3
"""pytable: writes the character classes of the Python that runs the Wi-Fi helpers, as the Rust port needs them
(rust/heimdall/src/cli/wifitools/py_table.rs): which characters str.isprintable() keeps (heimdall-wifi-notify's network
names), which are word characters and decimal digits to Python's re (\\w, \\b and \\d in heimdall-wifi-check's AS number
search) and int() (heimdall-wifi-guard's ports). The table follows the Python that runs the helpers (Arch's python).

    python3 rust/pytools/pytable.py > rust/heimdall/src/cli/wifitools/py_table.rs
"""
import platform
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(sys.maxunicode + 1):
        p = pred(chr(cp))
        if p and start is None:
            start = cp
        elif not p and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, sys.maxunicode))
    return out


def table(name, doc, rs):
    print("/// %s" % doc)
    print("pub static %s: &[(u32, u32)] = &[" % name)
    for a, b in rs:
        print("    (0x%04X, 0x%04X)," % (a, b))
    print("];\n")


decimal = ranges(str.isdecimal)
for a, b in decimal:
    # every run of decimal digits starts at a zero and holds whole tens, so a digit's value is (c - start) % 10
    assert unicodedata.decimal(chr(a)) == 0 and (b - a + 1) % 10 == 0, hex(a)

print("// Generated by rust/pytools/pytable.py from Python %s (Unicode %s); do not edit.\n" % (platform.python_version(), unicodedata.unidata_version))
print('/// The Unicode version of the Python the table was written from.\npub const UNICODE: &str = "%s";\n' % unicodedata.unidata_version)
table("PRINTABLE", "Ranges of the characters `str.isprintable()` is true for.", ranges(str.isprintable))
table("WORD", "Ranges of the word characters of Python's `re` on text (`\\w`: `c.isalnum() or c == '_'`).", ranges(lambda c: c.isalnum() or c == "_"))
table("DECIMAL", "Ranges of the decimal digits (`str.isdecimal()`, `\\d` of `re`, what `int()` reads); each run starts at a zero.", decimal)
